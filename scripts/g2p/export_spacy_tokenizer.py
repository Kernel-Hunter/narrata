"""Export spaCy's English tokenizer rules (MIT, Copyright Explosion AI) as a TypeScript module.

misaki tokenizes with spaCy, so Narrata reproduces spaCy's English tokenizer: the prefix, suffix
and infix patterns, the URL pattern and the special cases. Run in a Python environment with
spaCy 3.8 and en_core_web_sm 3.8:

    python scripts/g2p/export_spacy_tokenizer.py > src/engine/g2p/misaki/spacy-rules.ts
"""
import json
import re
import spacy

ALLOWED_ESCAPES = set('^$\\.*+?()[]{}|/-')


def to_js(pattern: str) -> str:
    out = []
    i = 0
    pattern = pattern.replace('(?u)', '')
    while i < len(pattern):
        c = pattern[i]
        if c == '\\' and i + 1 < len(pattern):
            n = pattern[i + 1]
            if n == 'U':
                out.append('\\u{%X}' % int(pattern[i + 2:i + 10], 16))
                i += 10
                continue
            if n == 'u':
                out.append(pattern[i:i + 6])
                i += 6
                continue
            if n.isalnum() or n in ALLOWED_ESCAPES:
                out.append(c + n)
            else:
                out.append(n)
            i += 2
            continue
        out.append(c)
        i += 1
    js = ''.join(out)
    re.compile(pattern)  # sanity
    return js


nlp = spacy.load('en_core_web_sm', enable=[])
t = nlp.tokenizer
rules = {}
for k, v in sorted(t.rules.items()):
    orths = [x.get(65, x.get('ORTH')) for x in v]
    rules[k] = 1 if orths == [k] else orths
print('// Generated by scripts/g2p/export_spacy_tokenizer.py from spaCy %s (en_core_web_sm %s).' % (spacy.__version__, nlp.meta['version']))
print('// spaCy is MIT licensed, Copyright (C) 2016-2024 ExplosionAI GmbH, 2016 spaCy GmbH, 2015 Matthew Honnibal.')
print('/* eslint-disable */')
for name, p in (('PREFIX', t.prefix_search.__self__.pattern), ('SUFFIX', t.suffix_search.__self__.pattern), ('INFIX', t.infix_finditer.__self__.pattern), ('URL', t.url_match.__self__.pattern)):
    print('export const %s = %s;' % (name, json.dumps(to_js(p), ensure_ascii=False)))
print('/** Special cases: text -> tokens (1 means the text is one token). */')
print('export const SPECIAL: Record<string, 1 | string[]> = %s;' % json.dumps(rules, ensure_ascii=False, separators=(',', ':')))
